package vaultfilebackend

// Opt-in real-MinIO TLS smoke test for the S3 bridge.
//
// This test is skipped unless the harness (scripts/s3_minio_smoke.py) has
// started a local MinIO container and exported MINIO_SMOKE_ENDPOINT,
// MINIO_SMOKE_CA_FILE, MINIO_SMOKE_ACCESS_KEY and MINIO_SMOKE_SECRET_KEY. It
// is not a mock: every request goes to the real TLS endpoint. The bucket is
// provisioned and every bucket and object is removed through the AWS SDK with
// the same explicit synthetic credentials; the credential provider never
// chains to any other source.
//
// Run it with:
//
//	python3 scripts/s3_minio_smoke.py

import (
	"bytes"
	"context"
	"crypto/rand"
	"crypto/tls"
	"crypto/x509"
	"errors"
	"fmt"
	"net/http"
	"os"
	"strings"
	"sync"
	"testing"
	"time"

	"github.com/aws/aws-sdk-go-v2/aws"
	"github.com/aws/aws-sdk-go-v2/service/s3"
)

const (
	minioSmokeEnableEnv   = "MINIO_SMOKE_ENABLE"
	minioSmokeEndpointEnv = "MINIO_SMOKE_ENDPOINT"
	minioSmokeCAFileEnv   = "MINIO_SMOKE_CA_FILE"
	minioSmokeAccessEnv   = "MINIO_SMOKE_ACCESS_KEY"
	minioSmokeSecretEnv   = "MINIO_SMOKE_SECRET_KEY"
	minioSmokeRegion      = "us-east-1"
	minioSmokeTimeout     = 30 * time.Second
)

// minioSmokeEnv holds the harness-supplied endpoint and credentials. The
// values are synthetic, generated by the harness in a private temp directory
// and never persisted.
type minioSmokeEnv struct {
	endpoint    string
	accessKey   string
	secretKey   string
	rootCAs     *x509.CertPool
	httpClient  *http.Client
	credentials aws.CredentialsProvider
}

// requireMinioSmoke returns the harness environment, or skips the test when
// the harness has not opted in.
func requireMinioSmoke(t *testing.T) minioSmokeEnv {
	t.Helper()
	if os.Getenv(minioSmokeEnableEnv) != "1" {
		t.Skipf("real MinIO TLS smoke test is opt-in: run python3 scripts/s3_minio_smoke.py (sets %s=1)", minioSmokeEnableEnv)
	}
	var missing []string
	get := func(key string) string {
		v := os.Getenv(key)
		if v == "" {
			missing = append(missing, key)
		}
		return v
	}
	endpoint := get(minioSmokeEndpointEnv)
	caFile := get(minioSmokeCAFileEnv)
	accessKey := get(minioSmokeAccessEnv)
	secretKey := get(minioSmokeSecretEnv)
	if len(missing) > 0 {
		t.Fatalf("%s=1 but %s missing; use scripts/s3_minio_smoke.py", minioSmokeEnableEnv, strings.Join(missing, ", "))
	}

	// Trust exactly the harness's generated certificate: a real TLS handshake
	// that is verified, never disabled.
	pem, err := os.ReadFile(caFile)
	if err != nil {
		t.Fatalf("read MinIO CA file: %v", err)
	}
	roots := x509.NewCertPool()
	if !roots.AppendCertsFromPEM(pem) {
		t.Fatalf("MinIO CA file %s carries no PEM certificate", caFile)
	}
	client := &http.Client{
		Transport: &http.Transport{
			TLSClientConfig:   &tls.Config{RootCAs: roots, MinVersion: tls.VersionTLS12},
			ForceAttemptHTTP2: true,
		},
		Timeout: minioSmokeTimeout,
	}
	credentials := aws.CredentialsProviderFunc(func(context.Context) (aws.Credentials, error) {
		return aws.Credentials{AccessKeyID: accessKey, SecretAccessKey: secretKey, Source: "minio-smoke-synthetic"}, nil
	})
	return minioSmokeEnv{
		endpoint:    endpoint,
		accessKey:   accessKey,
		secretKey:   secretKey,
		rootCAs:     roots,
		httpClient:  client,
		credentials: credentials,
	}
}

// sdkClient returns an AWS SDK S3 client configured only from the harness
// environment: explicit endpoint, static credentials and the CA pool.
func (e minioSmokeEnv) sdkClient() *s3.Client {
	endpoint := e.endpoint
	return s3.New(s3.Options{
		Region:       minioSmokeRegion,
		BaseEndpoint: &endpoint,
		Credentials:  aws.NewCredentialsCache(e.credentials),
		UsePathStyle: true,
		HTTPClient:   e.httpClient,
	})
}

// newBackend builds a bridge backend through the production NewS3
// constructor with the same explicit credentials and CA pool.
func (e minioSmokeEnv) newBackend(t *testing.T, bucket string) Backend {
	t.Helper()
	b, err := NewS3(S3Config{
		Endpoint:     e.endpoint,
		Region:       minioSmokeRegion,
		Bucket:       bucket,
		Prefix:       "smoke",
		Credentials:  e.credentials,
		UsePathStyle: true,
		HTTPClient:   e.httpClient,
	})
	if err != nil {
		t.Fatalf("NewS3: %v", err)
	}
	t.Cleanup(func() { _ = b.Close() })
	return b
}

// provisionMinioSmokeBucket creates a unique bucket and registers removal of
// every object in it and of the bucket itself.
func provisionMinioSmokeBucket(t *testing.T, e minioSmokeEnv) string {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), minioSmokeTimeout)
	defer cancel()
	var suffix [8]byte
	if _, err := rand.Read(suffix[:]); err != nil {
		t.Fatalf("random bucket suffix: %v", err)
	}
	bucket := "locklark-s3-smoke-" + fmt.Sprintf("%x", suffix)
	client := e.sdkClient()
	if _, err := client.CreateBucket(ctx, &s3.CreateBucketInput{Bucket: aws.String(bucket)}); err != nil {
		t.Fatalf("provision bucket: %v", err)
	}
	t.Cleanup(func() {
		cleanupCtx, cancel := context.WithTimeout(context.Background(), minioSmokeTimeout)
		defer cancel()
		out, err := client.ListObjectsV2(cleanupCtx, &s3.ListObjectsV2Input{Bucket: aws.String(bucket)})
		if err != nil {
			t.Errorf("list smoke bucket for cleanup: %v", err)
			return
		}
		for _, obj := range out.Contents {
			if _, err := client.DeleteObject(cleanupCtx, &s3.DeleteObjectInput{
				Bucket: aws.String(bucket),
				Key:    obj.Key,
			}); err != nil {
				t.Errorf("delete %q for cleanup: %v", aws.ToString(obj.Key), err)
			}
		}
		if _, err := client.DeleteBucket(cleanupCtx, &s3.DeleteBucketInput{Bucket: aws.String(bucket)}); err != nil {
			t.Errorf("delete smoke bucket: %v", err)
		}
	})
	return bucket
}

// TestS3MinioTLSSmoke exercises the S3 bridge against a real local MinIO over
// TLS: create, read, duplicate create, a racing replace from two backend
// instances, a stale replace, and the final read.
func TestS3MinioTLSSmoke(t *testing.T) {
	env := requireMinioSmoke(t)
	bucket := provisionMinioSmokeBucket(t, env)
	ctx, cancel := context.WithTimeout(context.Background(), 2*minioSmokeTimeout)
	defer cancel()

	const name = "minio-smoke.bin"
	original := []byte("minio-smoke\x00original-value\xff\n")
	first := env.newBackend(t, bucket)
	second := env.newBackend(t, bucket)

	// CreateIfAbsent commits the first version.
	if err := first.CreateIfAbsent(ctx, name, original); err != nil {
		t.Fatalf("CreateIfAbsent: %v", err)
	}
	read := func(b Backend, what string) ReadResult {
		t.Helper()
		res, err := b.Read(ctx, name)
		if err != nil {
			t.Fatalf("%s: Read: %v", what, err)
		}
		return res
	}
	base := read(first, "after create")
	if !bytes.Equal(base.Bytes, original) {
		t.Fatalf("after create: bytes %q, want %q", base.Bytes, original)
	}
	if base.Revision.Zero() {
		t.Fatal("after create: Read returned an empty revision")
	}
	if !validStrongETag(string(base.Revision)) {
		t.Fatalf("after create: revision %q is not one strong quoted ETag", base.Revision)
	}

	// A duplicate create must be refused without touching the stored version.
	if err := first.CreateIfAbsent(ctx, name, []byte("duplicate")); !errors.Is(err, ErrConflict) {
		t.Fatalf("duplicate CreateIfAbsent: err = %v, want ErrConflict (a service that ignores If-None-Match is unsupported)", err)
	}
	afterDuplicate := read(second, "after duplicate create")
	if !bytes.Equal(afterDuplicate.Bytes, original) || afterDuplicate.Revision != base.Revision {
		t.Fatalf("duplicate create changed the version: bytes %q revision %q, want %q / %q",
			afterDuplicate.Bytes, afterDuplicate.Revision, original, base.Revision)
	}

	// Race two ReplaceIfVersion calls from separate backend instances with the
	// same revision. Exactly one must commit; the other must be ErrConflict.
	winner := []byte("minio-smoke-winner")
	loser := []byte("minio-smoke-loser")
	start := make(chan struct{})
	type outcome struct {
		by  string
		val []byte
		err error
	}
	results := make(chan outcome, 2)
	var wg sync.WaitGroup
	for _, w := range []struct {
		by  string
		b   Backend
		val []byte
	}{{"first", first, winner}, {"second", second, loser}} {
		wg.Add(1)
		go func() {
			defer wg.Done()
			<-start
			results <- outcome{by: w.by, val: w.val, err: w.b.ReplaceIfVersion(ctx, name, base.Revision, w.val)}
		}()
	}
	close(start)
	wg.Wait()
	close(results)

	var committed []outcome
	for res := range results {
		switch {
		case res.err == nil:
			committed = append(committed, res)
		case errors.Is(res.err, ErrConflict):
		default:
			// ErrUnknown is not proof of a lost race; a service that ignores
			// If-Match (a second committed write) or any other outcome fails
			// the smoke test.
			t.Fatalf("racing ReplaceIfVersion by %s: unexpected err = %v", res.by, res.err)
		}
	}
	if len(committed) != 1 {
		t.Fatalf("racing ReplaceIfVersion: %d committed, want exactly 1 (a service that ignores If-Match is unsupported)", len(committed))
	}
	won := committed[0]
	afterRace := read(first, "after race")
	if !bytes.Equal(afterRace.Bytes, won.val) {
		t.Fatalf("after race: stored bytes %q, want the winner's (%s) %q", afterRace.Bytes, won.by, won.val)
	}
	if afterRace.Revision == base.Revision {
		t.Fatalf("after race: revision unchanged (%q) after a committed replace", afterRace.Revision)
	}

	// A later replace with the now-stale original revision must conflict.
	if err := second.ReplaceIfVersion(ctx, name, base.Revision, []byte("minio-smoke-stale")); !errors.Is(err, ErrConflict) {
		t.Fatalf("stale ReplaceIfVersion: err = %v, want ErrConflict (a service that ignores If-Match is unsupported)", err)
	}
	final := read(second, "final")
	if !bytes.Equal(final.Bytes, won.val) || final.Revision != afterRace.Revision {
		t.Fatalf("final version: bytes %q revision %q, want %q / %q",
			final.Bytes, final.Revision, won.val, afterRace.Revision)
	}
}
